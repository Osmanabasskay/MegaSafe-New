// ─── CSV helpers ──────────────────────────────────────────────────────────────

const csvEsc = (v: string | number | null | undefined): string => {
  const s = String(v ?? '');
  return s.includes(',') || s.includes('"') || s.includes('\n') ? `"${s.replace(/"/g, '""')}"` : s;
};

const buildCsv = (
  headers: string[],
  rows: Array<Array<string | number | null | undefined>>,
  meta: { generatedBy: string; type: string; dateRange: string }
): string => {
  const footer: string[] = [
    '',
    `# report_type,${csvEsc(meta.type)}`,
    `# date_range,${csvEsc(meta.dateRange)}`,
    `# generated_by,${csvEsc(meta.generatedBy)}`,
    `# generated_at,${new Date().toISOString()}`,
  ];
  return [headers.map(csvEsc).join(','), ...rows.map((r) => r.map(csvEsc).join(',')), ...footer].join('\n');
};

const csvResponse = (csv: string, name: string) =>
  new NextResponse(csv, {
    headers: {
      'Content-Type': 'text/csv; charset=utf-8',
      'Content-Disposition': `attachment; filename="miosusu-${name}-${Date.now()}.csv"`,
    },
  });

// ─── PDF helpers ──────────────────────────────────────────────────────────────

const pdfEsc = (s: string) => s.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');

interface PdfSection { heading?: string; lines: string[]; }

const buildPdf = (title: string, dateRange: string, adminNote: string, sections: PdfSection[]): string => {
  const allLines: string[] = [
    `Mi Osusu Super Admin Report`,
    `Report: ${title}`,
    `Date Range: ${dateRange}`,
    `Generated: ${new Date().toUTCString()}`,
    `Generated by: ${adminNote}`,
    ``,
    `VERIFICATION: Generated from live database data via secure server-side query. No data was modified.`,
    ``,
    ...sections.flatMap((s) => [...(s.heading ? [`=== ${s.heading} ===`] : []), ...s.lines, ``]),
  ];
  const linesPerPage = 50;
  const pages: string[] = [];
  for (let i = 0; i < allLines.length; i += linesPerPage) {
    const chunk = allLines.slice(i, i + linesPerPage);
    pages.push(chunk.map((line, idx) => `BT /F1 10 Tf 50 ${740 - idx * 14} Td (${pdfEsc(line.slice(0, 110))}) Tj ET`).join('\n'));
  }
  const objectsBase = [
    `<< /Type /Catalog /Pages 2 0 R >>`,
    `<< /Type /Pages /Kids [${pages.map((_, i) => `${i + 3} 0 R`).join(' ')}] /Count ${pages.length} >>`,
    `<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>`,
  ];
  const pageObjects = pages.map((_c, i) => `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents ${objectsBase.length + 1 + i + 1} 0 R >>`);
  const contentObjects = pages.map((content) => `<< /Length ${content.length} >>\nstream\n${content}\nendstream`);
  const allObjects = [...objectsBase, ...pageObjects, ...contentObjects];
  const offsets: number[] = [];
  let pdf = '%PDF-1.4\n';
  allObjects.forEach((obj, i) => { offsets[i] = pdf.length; pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`; });
  const xrefStart = pdf.length;
  pdf += `xref\n0 ${allObjects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 0; i < allObjects.length; i++) pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  pdf += `trailer << /Size ${allObjects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;
  return pdf;
};

const pdfResponse = (pdf: string, name: string) =>
  new Response(pdf, {
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="miosusu-${name}-${Date.now()}.pdf"`,
    },
  });

// ─── Route ────────────────────────────────────────────────────────────────────

export async function GET(request: Request) {
  // Super-admin gate (redirects to /login if not authorised) + ledger context.
  const { userId, userName, svc } = await requireSuperAdmin();

  const url = new URL(request.url);
  const format = (url.searchParams.get('format') ?? 'csv').toLowerCase();
  const from = url.searchParams.get('from') || 'all-time';
  const to = url.searchParams.get('to') || new Date().toISOString().slice(0, 10);
  const reportType = url.searchParams.get('type') || 'summary';
  const dateRange = `${from} to ${to}`;
  const meta = { generatedBy: userName, type: reportType, dateRange };

  // ── Audit-log EVERY export (Phase 13 rule) ──
  await logAdminAction({
    supabase: svc, adminUserId: userId, adminName: userName,
    action: 'export_generated', tableName: 'admin_actions',
    reason: `Export ${reportType} (${format})`,
    metadata: { type: reportType, format, from, to },
  });

  // ── Risk events ──
  if (reportType === 'risk_events') {
    const events = await getLiveRiskEvents({ limit: 500 });
    const csv = buildCsv(
      ['Severity', 'Score', 'Event Type', 'Target', 'Reason', 'Status', 'Created'],
      events.map((e) => [e.severity, e.riskScore, e.eventType, e.targetName ?? e.targetUserId ?? '-', e.reason ?? '-', e.status, e.createdAt.slice(0, 19)]),
      meta,
    );
    return format === 'pdf'
      ? pdfResponse(buildPdf('Risk Event Report', dateRange, userName, [{ heading: 'Risk Events', lines: events.map((e) => `[${e.severity.toUpperCase()} ${e.riskScore}] ${e.eventType} | ${e.status} | ${e.createdAt.slice(0, 10)}`) }]), 'risk-events')
      : csvResponse(csv, 'risk-events');
  }

  // ── Security events ──
  if (reportType === 'security_events') {
    const { events } = await getSecurityEvents({ page: 1 });
    const csv = buildCsv(
      ['Severity', 'Event Type', 'User', 'IP', 'Reason', 'Status', 'Created'],
      events.map((e) => [e.severity, e.eventType, e.userId ?? '-', e.ipAddress ?? '-', e.reason ?? '-', e.status, e.createdAt.slice(0, 19)]),
      meta,
    );
    return format === 'pdf'
      ? pdfResponse(buildPdf('Security Event Report', dateRange, userName, [{ heading: 'Security Events', lines: events.map((e) => `[${e.severity}] ${e.eventType} | ${e.status} | ${e.createdAt.slice(0, 10)}`) }]), 'security-events')
      : csvResponse(csv, 'security-events');
  }

  // ── Admin activity ──
  if (reportType === 'admin_activity') {
    const rows = await getAdminActivity({ limit: 500 });
    const csv = buildCsv(
      ['Admin', 'Action', 'Target', 'Reason', 'Risk', 'Status', 'IP', 'When'],
      rows.map((r) => [r.adminName ?? '-', r.action, r.targetName ?? r.targetUserId ?? '-', r.reason ?? '-', r.riskScore, r.status, r.ipAddress ?? '-', r.createdAt.slice(0, 19)]),
      meta,
    );
    return format === 'pdf'
      ? pdfResponse(buildPdf('Admin Activity Report', dateRange, userName, [{ heading: 'Admin Actions', lines: rows.map((r) => `${r.adminName ?? 'Admin'} | ${r.action} | ${r.status} | ${r.createdAt.slice(0, 10)}`) }]), 'admin-activity')
      : csvResponse(csv, 'admin-activity');
  }

  // ── Audit log ──
  if (reportType === 'audit_log') {
    const { rows } = await getAuditRows({ page: 1 });
    const csv = buildCsv(
      ['Actor', 'Action', 'Table', 'Record', 'IP', 'When'],
      rows.map((r) => [r.actor, r.action, r.tableName, r.recordId ?? '-', r.ipAddress ?? '-', r.createdAt.slice(0, 19)]),
      meta,
    );
    return csvResponse(csv, 'audit-log');
  }

  // ── KYC ──
  if (reportType === 'kyc') {
    const { applications } = await getKycApplications({ pageSize: 500 });
    const csv = buildCsv(
      ['ID', 'User', 'Full Name', 'Phone', 'Status', 'Doc Type', 'Submitted', 'Reviewed'],
      applications.map((a) => [a.id.slice(0, 8), a.userId.slice(0, 8), a.fullName, a.phone, a.status, a.documentType, a.submittedAt.slice(0, 10), a.reviewedAt?.slice(0, 10) ?? '-']),
      meta,
    );
    return csvResponse(csv, 'kyc');
  }

  // ── Collectors ──
  if (reportType === 'collectors') {
    const collectors = await getCollectorMonitor();
    const csv = buildCsv(
      ['User ID', 'Name', 'Status', 'Commission Rate', 'Disputes'],
      collectors.map((c) => [c.userId.slice(0, 8), c.name, c.status, c.commissionRate, c.disputeCount]),
      meta,
    );
    return csvResponse(csv, 'collectors');
  }

  // ── Groups ──
  if (reportType === 'groups') {
    const groups = await getGroupMonitor();
    const csv = buildCsv(
      ['ID', 'Name', 'Creator', 'Members', 'Volume (NLe)', 'Status'],
      groups.map((g) => [g.id.slice(0, 8), g.name, g.creatorName, g.members, g.volumeNLe.toFixed(2), g.status]),
      meta,
    );
    return csvResponse(csv, 'groups');
  }

  // ── Contributions ──
  if (reportType === 'contributions') {
    const { contributions } = await getOsusuContributions({ page: 1 });
    const csv = buildCsv(
      ['ID', 'Group', 'Member', 'Amount (NLe)', 'Status', 'Method', 'Created'],
      contributions.map((c) => [c.id.slice(0, 8), c.groupName, c.memberId.slice(0, 8), c.amount.toFixed(2), c.status, c.paymentMethod ?? '-', c.createdAt.slice(0, 10)]),
      meta,
    );
    return csvResponse(csv, 'contributions');
  }

  // ── Payments (mobile money) ──
  if (reportType === 'payments' || reportType === 'transactions') {
    const { mobileMoneyTxs } = await getPaymentsSummary({ page: 1 });
    const csv = buildCsv(
      ['ID', 'User', 'Provider', 'Reference', 'Direction', 'Amount (NLe)', 'Status', 'Created'],
      mobileMoneyTxs.map((t) => [t.id.slice(0, 8), t.userId.slice(0, 8), t.provider, t.providerReference ?? '-', t.direction, t.amount.toFixed(2), t.status, t.createdAt.slice(0, 10)]),
      meta,
    );
    return csvResponse(csv, reportType);
  }

  // ── Disputes ──
  if (reportType === 'disputes') {
    const { disputes } = await getDisputes({ page: 1 });
    if (format === 'csv') {
      const csv = buildCsv(
        ['ID', 'Category', 'Title', 'Status', 'Priority', 'Created', 'Resolved'],
        disputes.map((d) => [d.id.slice(0, 8), d.category, d.title, d.status, d.priority, d.createdAt.slice(0, 10), d.resolvedAt?.slice(0, 10) ?? '-']),
        meta,
      );
      return csvResponse(csv, 'disputes');
    }
    return pdfResponse(buildPdf('Dispute Report', dateRange, userName, [{ heading: 'Disputes', lines: disputes.map((d) => `[${d.status.toUpperCase()}] ${d.title} | ${d.category} | ${d.createdAt.slice(0, 10)}`) }]), 'disputes');
  }

  // ── Withdrawals / payouts ──
  if (reportType === 'withdrawals' || reportType === 'payouts') {
    const { withdrawals } = await getWithdrawals({ page: 1 });
    if (format === 'csv') {
      const csv = buildCsv(
        ['ID', 'User', 'Amount (NLe)', 'Provider', 'Destination', 'Status', 'Requested'],
        withdrawals.map((w) => [w.id.slice(0, 8), w.userId.slice(0, 8), w.amount.toFixed(2), w.destinationProvider, w.destinationNumber, w.status, w.requestedAt.slice(0, 10)]),
        meta,
      );
      return csvResponse(csv, 'payouts');
    }
    return pdfResponse(buildPdf('Payout Report', dateRange, userName, [{ heading: 'Withdrawal Requests', lines: withdrawals.map((w) => `[${w.status.toUpperCase()}] NLe ${w.amount.toFixed(2)} via ${w.destinationProvider} | ${w.requestedAt.slice(0, 10)}`) }]), 'payouts');
  }

  // ── Users / summary (default) ──
  if (reportType === 'users' || reportType === 'summary') {
    const [{ kpis, countryBreakdown }, { users }] = await Promise.all([getDashboardKpis(), getUsers({ pageSize: 500 })]);
    if (format === 'csv') {
      const csv = buildCsv(
        ['Name', 'Phone', 'Email', 'KYC Status', 'Role', 'Status', 'Joined'],
        users.map((u) => [u.name, u.phone, u.email, u.kycStatus, u.role, u.status, u.createdAt.slice(0, 10)]),
        meta,
      );
      return csvResponse(csv, 'users');
    }
    return pdfResponse(buildPdf('Summary + User Report', dateRange, userName, [
      { heading: 'Platform Summary', lines: [
        `Total Users: ${kpis.users.total}`, `New Today: ${kpis.users.newToday}`, `Pending KYC: ${kpis.users.pendingKyc}`,
        `Active Groups: ${kpis.groups.active}`, `Open Disputes: ${kpis.disputes.open}`,
        `Platform Commissions (NLe): ${kpis.revenue.totalCommissionsNLe.toFixed(2)}`, `Savings Balance (NLe): ${kpis.savings.totalBalanceNLe.toFixed(2)}`,
      ] },
      { heading: 'Country Distribution', lines: countryBreakdown.map((c) => `${c.country}: ${c.value} users`) },
      { heading: 'User List (first 500)', lines: users.map((u) => `${u.name} | ${u.phone} | KYC:${u.kycStatus} | ${u.status}`) },
    ]), 'report');
  }

  // Fallback: platform summary metrics
  const { kpis } = await getDashboardKpis();
  const rows: Array<[string, string | number]> = [
    ['Date Range', dateRange], ['Total Users', kpis.users.total], ['New Users Today', kpis.users.newToday],
    ['Pending KYC', kpis.users.pendingKyc], ['Active Groups', kpis.groups.active], ['Open Disputes', kpis.disputes.open],
    ['Pending Withdrawals Count', kpis.withdrawals.pendingCount], ['Pending Withdrawals (NLe)', kpis.withdrawals.pendingAmountNLe.toFixed(2)],
    ['Platform Commissions (NLe)', kpis.revenue.totalCommissionsNLe.toFixed(2)], ['Savings Balance (NLe)', kpis.savings.totalBalanceNLe.toFixed(2)],
    ['Failed Topups 24h', kpis.risk.failedTopups24h], ['Rate Limit Events 24h', kpis.risk.rateLimitEvents24h],
  ];
  return format === 'pdf'
    ? pdfResponse(buildPdf('Platform Summary', dateRange, userName, [{ heading: 'Key Metrics', lines: rows.map(([k, v]) => `${k}: ${v}`) }]), 'summary')
    : csvResponse(buildCsv(['Metric', 'Value'], rows, meta), 'summary');
}
